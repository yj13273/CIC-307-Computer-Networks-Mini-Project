/**
 * Cisco IOS Switch Configuration Generator
 * Generates copy-paste ready Cisco IOS syntax for L2/L3 switches
 */

export function generateSwitchConfig({
  hostname,
  model = 'Catalyst 9300-48P',
  vlans = [],
  trunks = [],
  accessPorts = [],
  poeEnabled = false,
  rapidPvst = true
}) {
  const lines = [
    `! ========================================================`,
    `! Cisco IOS Switch Configuration: ${hostname}`,
    `! Platform: ${model}`,
    `! Generated by NetArchitect Configuration Engine`,
    `! ========================================================`,
    `hostname ${hostname}`,
    `!`,
    `service timestamps debug datetime msec`,
    `service timestamps log datetime msec`,
    `no service password-encryption`,
    `!`,
    `spanning-tree mode ${rapidPvst ? 'rapid-pvst' : 'pvst'}`,
    `spanning-tree portfast default`,
    `spanning-tree portfast bpduguard default`,
    `spanning-tree extend system-id`,
    `!`
  ];

  // VLAN definitions
  if (vlans.length > 0) {
    lines.push(`! --- VLAN Database Configuration ---`);
    for (const vlan of vlans) {
      if (vlan.vlanId) {
        lines.push(`vlan ${vlan.vlanId}`);
        lines.push(` name ${vlan.name.replace(/\s+/g, '_')}`);
      }
    }
    lines.push(`!`);
  }

  // Trunk ports
  if (trunks.length > 0) {
    lines.push(`! --- 802.1Q Trunk Interfaces ---`);
    for (const trunk of trunks) {
      lines.push(`interface ${trunk.port}`);
      lines.push(` description Uplink to ${trunk.remoteDevice || 'Distribution Core'}`);
      lines.push(` switchport trunk encapsulation dot1q`);
      lines.push(` switchport mode trunk`);
      lines.push(` switchport trunk allowed vlan ${trunk.allowedVlans || 'all'}`);
      lines.push(` switchport nonegotiate`);
      lines.push(` spanning-tree link-type point-to-point`);
      lines.push(` no shutdown`);
      lines.push(`!`);
    }
  }

  // Access ports
  if (accessPorts.length > 0) {
    lines.push(`! --- Access Edge Ports ---`);
    for (const acc of accessPorts) {
      lines.push(`interface range ${acc.range}`);
      lines.push(` description ${acc.description || 'Endpoint Access'}`);
      lines.push(` switchport mode access`);
      lines.push(` switchport access vlan ${acc.vlanId}`);
      if (poeEnabled) {
        lines.push(` power inline auto`);
      }
      lines.push(` spanning-tree portfast`);
      lines.push(` spanning-tree bpduguard enable`);
      lines.push(` no shutdown`);
      lines.push(`!`);
    }
  }

  lines.push(`line con 0`);
  lines.push(` logging synchronous`);
  lines.push(`line vty 0 4`);
  lines.push(` transport input ssh`);
  lines.push(`!`);
  lines.push(`end`);
  lines.push(`write memory`);

  return lines.join('\n');
}

