/**
 * Cisco IOS Router Configuration Generator
 */

export function generateRouterConfig({
  hostname,
  model = 'ISR 4451-X',
  profileId,
  subnets = [],
  routing = {},
  bgpPeering = null,
  ipsecEnabled = false
}) {
  const lines = [
    `! ========================================================`,
    `! Cisco IOS Router Configuration: ${hostname}`,
    `! Platform: ${model}`,
    `! Generated by NetArchitect Configuration Engine`,
    `! ========================================================`,
    `hostname ${hostname}`,
    `!`,
    `service timestamps debug datetime msec`,
    `service timestamps log datetime msec`,
    `no service password-encryption`,
    `ip routing`,
    `ip cef`,
    `!`
  ];

  // IPsec VPN Crypto Config if enabled
  if (ipsecEnabled) {
    lines.push(`! --- IPsec IKEv2 Cryptographic Policy (RFC 7296) ---`);
    lines.push(`crypto ikev2 proposal IKEV2-PROPOSAL-ENTERPRISE`);
    lines.push(` encryption aes-gcm-256`);
    lines.push(` prf sha384`);
    lines.push(` group 19`);
    lines.push(`!`);
    lines.push(`crypto ikev2 policy IKEV2-POLICY-ENTERPRISE`);
    lines.push(` proposal IKEV2-PROPOSAL-ENTERPRISE`);
    lines.push(`!`);
    lines.push(`crypto ikev2 keyring IKEV2-KEYRING`);
    lines.push(` peer WAN-PEERS`);
    lines.push(`  address 0.0.0.0 0.0.0.0`);
    lines.push(`  pre-shared-key EnterpriseStrongSecretKey2026!`);
    lines.push(`!`);
    lines.push(`crypto ikev2 profile IKEV2-PROFILE-WAN`);
    lines.push(` match identity remote any`);
    lines.push(` authentication remote pre-share`);
    lines.push(` authentication local pre-share`);
    lines.push(` keyring local IKEV2-KEYRING`);
    lines.push(`!`);
    lines.push(`crypto ipsec transform-set TS-AES256-GCM esp-gcm 256`);
    lines.push(` mode tunnel`);
    lines.push(`!`);
    lines.push(`crypto ipsec profile IPSEC-PROFILE-WAN`);
    lines.push(` set transform-set TS-AES256-GCM`);
    lines.push(` set ikev2-profile IKEV2-PROFILE-WAN`);
    lines.push(`!`);
    lines.push(`interface Tunnel1`);
    lines.push(` description Secure IPsec WAN Overlay Tunnel`);
    lines.push(` ip address 10.255.255.1 255.255.255.252`);
    lines.push(` tunnel source GigabitEthernet0/0/0`);
    lines.push(` tunnel mode ipsec ipv4`);
    lines.push(` tunnel protection ipsec profile IPSEC-PROFILE-WAN`);
    lines.push(` ip ospf 1 area 0`);
    lines.push(`!`);
  }

  // Interfaces
  lines.push(`! --- Physical and Sub-Interface Configuration ---`);
  lines.push(`interface GigabitEthernet0/0/0`);
  lines.push(` description WAN Uplink Interface`);
  lines.push(` ip address 198.51.100.2 255.255.255.252`);
  lines.push(` no shutdown`);
  lines.push(`!`);

  lines.push(`interface GigabitEthernet0/0/1`);
  lines.push(` description Core LAN Trunk Interface`);
  lines.push(` no ip address`);
  lines.push(` no shutdown`);
  lines.push(`!`);

  // Inter-VLAN Sub-interfaces for campus
  for (const sub of subnets) {
    if (!sub.vlanId) continue;
    lines.push(`interface GigabitEthernet0/0/1.${sub.vlanId}`);
    lines.push(` description Sub-interface for ${sub.name}`);
    lines.push(` encapsulation dot1Q ${sub.vlanId}`);
    lines.push(` ip address ${sub.defaultGateway} ${sub.netmask}`);
    lines.push(` no shutdown`);
    lines.push(`!`);
  }

  // OSPF Routing Process
  lines.push(`! --- Dynamic Routing Protocol: OSPF Process ---`);
  lines.push(`router ospf 1`);
  lines.push(` router-id 1.1.1.1`);
  lines.push(` auto-cost reference-bandwidth 100000`); // 100 Gbps reference bandwidth for 10G links
  lines.push(` log-adjacency-changes`);

  if (profileId === 'global-wan') {
    // Multi-Area OSPF with route summarization
    lines.push(` area 1 range 10.1.0.0 255.255.0.0`);
    lines.push(` area 2 range 10.2.0.0 255.255.0.0`);
    lines.push(` network 198.51.100.0 0.0.0.3 area 0`);
    for (const sub of subnets) {
      const area = sub.vlanId === 500 ? '1' : (sub.vlanId === 200 ? '2' : '0');
      lines.push(` network ${sub.networkAddress} ${sub.wildcardMask} area ${area}`);
    }
  } else {
    // Single Area OSPF (Area 0)
    for (const sub of subnets) {
      lines.push(` network ${sub.networkAddress} ${sub.wildcardMask} area 0`);
    }
  }
  lines.push(`!`);

  // BGP Configuration if applicable
  if (bgpPeering) {
    lines.push(`! --- Border Gateway Protocol (BGP-4) Peering ---`);
    lines.push(`router bgp ${bgpPeering.enterpriseAsn || 65000}`);
    lines.push(` bgp router-id 1.1.1.1`);
    lines.push(` bgp log-neighbor-changes`);
    lines.push(` neighbor 198.51.100.1 remote-as ${bgpPeering.cloudAsn || 64512}`);
    lines.push(` neighbor 198.51.100.1 description AWS Transit Gateway Peering`);
    lines.push(` !`);
    lines.push(` address-family ipv4`);
    lines.push(`  network 10.0.0.0 mask 255.252.0.0`); // Summarized route advertised
    lines.push(`  neighbor 198.51.100.1 activate`);
    lines.push(`  neighbor 198.51.100.1 route-map RM-ADVERTISE-SUMMARY out`);
    lines.push(` exit-address-family`);
    lines.push(`!`);
    lines.push(`ip route 10.0.0.0 255.252.0.0 Null0 254`); // Discard route for BGP summarization
    lines.push(`!`);
  }

  lines.push(`line con 0`);
  lines.push(` logging synchronous`);
  lines.push(`line vty 0 4`);
  lines.push(` transport input ssh`);
  lines.push(`!`);
  lines.push(`end`);
  lines.push(`write memory`);

  return lines.join('\n');
}

